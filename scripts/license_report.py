"""Write a third-party licence report for the Python environment and the frontend's npm packages.

    backend\\.venv\\Scripts\\python scripts\\license_report.py            (Windows)
    backend/.venv/bin/python scripts/license_report.py                   (Linux/macOS)

Output: THIRD_PARTY_LICENSES.md in the repository root. Packages whose licence is strong copyleft (GPL/AGPL) are
listed first so they can be reviewed before distributing Local AI Lab; weak copyleft (LGPL/MPL/EPL) and unknown
licences are flagged for review too. The report reads package metadata – it is an aid, not legal advice.
Exit code 1 if a strong-copyleft package is installed (use --allow-copyleft to only warn).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from importlib.metadata import distributions
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRONG = re.compile(r"\b(A?GPL|GNU (AFFERO )?GENERAL PUBLIC)\b", re.IGNORECASE)
WEAK = re.compile(r"\b(LGPL|LESSER GENERAL|MPL|MOZILLA|EPL|ECLIPSE|CDDL)\b", re.IGNORECASE)


TEXT_PATTERNS = [("GNU AFFERO GENERAL PUBLIC", "AGPL (from licence file)"), ("GNU LESSER GENERAL PUBLIC", "LGPL (from licence file)"),
                 ("GNU GENERAL PUBLIC", "GPL (from licence file)"), ("Mozilla Public License", "MPL-2.0 (from licence file)"),
                 ("Apache License", "Apache-2.0 (from licence file)"),
                 ("Permission is hereby granted, free of charge", "MIT (from licence file)"),
                 ("Redistribution and use in source and binary forms", "BSD (from licence file)"),
                 ("Permission to use, copy, modify, and/or distribute", "ISC (from licence file)")]


def _from_files(dist) -> str:
    for f in dist.files or []:
        name = f.name.upper()
        if name.startswith(("LICENSE", "LICENCE", "COPYING")):
            try:
                text = f.locate().read_text(encoding="utf-8", errors="ignore")[:4000]
            except (OSError, ValueError):
                continue
            for pat, lic in TEXT_PATTERNS:
                if pat.lower() in text.lower():
                    return lic
    return ""


def python_packages() -> list[dict]:
    out = []
    for d in distributions():
        m = d.metadata
        name = m.get("Name") or "?"
        lic = (m.get("License-Expression") or "").strip()
        classifiers = [c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License")]
        if not lic:
            raw = (m.get("License") or "").strip()
            lic = raw.splitlines()[0][:80] if raw and len(raw) < 200 else ""
        if not lic and classifiers:
            lic = "; ".join(classifiers)
        if not lic:
            lic = _from_files(d)
        out.append({"name": name, "version": m.get("Version") or "", "license": lic or "UNKNOWN",
                    "classifiers": classifiers})
    return sorted({p["name"].lower(): p for p in out}.values(), key=lambda p: p["name"].lower())


def npm_packages() -> list[dict]:
    lock = ROOT / "frontend" / "package-lock.json"
    if not lock.exists():
        return []
    data = json.loads(lock.read_text(encoding="utf-8"))
    out = []
    for path, info in (data.get("packages") or {}).items():
        if not path.startswith("node_modules/"):
            continue
        lic = info.get("license") or "UNKNOWN"
        out.append({"name": path.split("node_modules/")[-1], "version": info.get("version", ""),
                    "license": lic if isinstance(lic, str) else json.dumps(lic), "dev": bool(info.get("dev"))})
    return sorted(out, key=lambda p: p["name"])


def classify(lic: str, classifiers: list[str] | None = None) -> str:
    text = " ".join([lic] + (classifiers or []))
    if "Dual Licensed" in lic or " OR " in lic.upper():
        if STRONG.search(text) and not re.search(r"\b(MIT|BSD|Apache|ISC)\b", text):
            return "strong copyleft (dual-licensed) – review"
    if STRONG.search(text) and not WEAK.search(text):
        return "STRONG COPYLEFT – review before distributing"
    if WEAK.search(text):
        return "weak copyleft – review"
    if lic == "UNKNOWN":
        return "unknown – check"
    return "permissive"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-copyleft", action="store_true")
    ap.add_argument("--output", default=str(ROOT / "THIRD_PARTY_LICENSES.md"))
    args = ap.parse_args()
    py = python_packages()
    npm = npm_packages()
    for p in py:
        p["status"] = classify(p["license"], p["classifiers"])
    for p in npm:
        p["status"] = classify(p["license"])
    flagged = [p for p in py + npm if p["status"] != "permissive"]
    lines = ["# Third-party licences", "",
             "Generated by `scripts/license_report.py` from installed package metadata. This is an aid for review, "
             "not legal advice. Local AI Lab's own licence is chosen by its owner (see docs/LEGAL_AND_LICENSING.md).", "",
             "Python packages come from `backend/requirements.txt` plus their dependencies; development-only tools "
             "(pytest, ruff, hypothesis, openai, skl2onnx, pip-audit) are only needed to run the tests. npm packages "
             "marked *dev* are build tools and are not shipped in the built web interface.", "",
             "Models (LLMs, embedding models, image backbones) are **not** covered here – each has its own licence; "
             "see `docs/LEGAL_AND_LICENSING.md` and the Setup → Models page.", "",
             "## Needs review", ""]
    lines += [f"- **{p['name']} {p['version']}** – {p['license']} – {p['status']}" for p in flagged] or ["- none"]
    lines += ["", "## Python packages", "", "| Package | Version | Licence | Status |", "|---|---|---|---|"]
    lines += [f"| {p['name']} | {p['version']} | {p['license'][:70]} | {p['status']} |" for p in py]
    lines += ["", "## npm packages (frontend)", "", "| Package | Version | Licence | Dev only | Status |",
              "|---|---|---|---|---|"]
    lines += [f"| {p['name']} | {p['version']} | {p['license']} | {'yes' if p['dev'] else ''} | {p['status']} |"
              for p in npm]
    Path(args.output).write_text("\n".join(lines) + "\n", encoding="utf-8")
    strong = [p for p in flagged if "STRONG" in p["status"] or "strong" in p["status"]]
    print(f"{len(py)} Python + {len(npm)} npm packages; {len(flagged)} to review; written {args.output}")
    for p in flagged:
        print(f"  review: {p['name']} {p['version']} – {p['license'][:60]} ({p['status']})")
    return 1 if strong and not args.allow_copyleft else 0


if __name__ == "__main__":
    sys.exit(main())
